-- 0133_username_backfill.sql
-- HUMAN-APPLIED. Night run #2 (2026-10-17), PR D. NOT applied to any live database by the PR.
--
-- WHY. Before 2026-10-16 (#645) new `user_profiles.username` values were derived from the account
-- e-mail (`email.split("@")[0]`, with a random `_NNNN` / `_<timestamp>` suffix on collision). #645 stopped
-- creating them and stopped showing a username as another person's display name, but the existing
-- rows still hold e-mail fragments (e.g. "augusto+demo2") and still surface as an `@handle` in the
-- invite flows (staff invite, family/caregiver, walk invitees). This rewrites ONLY those rows.
--
-- WHAT. For every profile whose username is e-mail-derived, set a fresh unique username built from the
-- person's display name (else their first pet's name, else a random neutral `pawpi_xxxxxx`) — the same
-- shape the app now generates (lowercase a-z0-9, accents folded, <= 24 chars). The old value goes to a
-- tiny audit table so the change is reversible. Nothing else changes: ids, auth rows, pets, handles,
-- follows, friendships, packs, notifications and invites all key on ids, never on the username text.
--
-- E-MAIL-DERIVED means ANY of (case-insensitive):
--   * the username contains '@' or '+';
--   * the username equals the local part of the account's e-mail;
--   * the username is that local part followed by '_' and 1–13 digits (the collision suffixes).
-- System accounts (pawpi_welcome, pawpi_directory) are never touched.
--
-- SAFE TO RE-RUN. A renamed row no longer matches, and a replacement is never chosen if it would itself
-- match the e-mail pattern for that user (so a second run is a no-op). A replacement never collides
-- (case-insensitively) with ANY existing username or pet handle, a reserved word, or another
-- replacement made in the same run.
--
-- RUN AS a role that bypasses RLS (the Supabase SQL editor's `postgres`): user_profiles is FORCE RLS.
-- Schema impact: ONE new audit table (RLS enabled + FORCED, owner-scoped SELECT only; the app cannot
-- write it). No grants, no existing RLS/policy/column/function changes.
-- Verify: supabase/verify_0133.sql (every row PASS). Runbook: docs/db-migration-runbook-0133-username-backfill.md.

-- ── 1. audit table (old value kept so this is reversible) ─────────────────────
create table if not exists user_profile_username_backfill_audit (
  id             integer generated by default as identity primary key,
  user_id        integer not null references user_profiles(id) on delete cascade,
  old_username   text not null,
  new_username   text not null,
  backfilled_at  timestamptz not null default now()
);

alter table user_profile_username_backfill_audit enable row level security;
alter table user_profile_username_backfill_audit force row level security;

-- Owner can read their own audit row; nobody (via the app role) can write it.
drop policy if exists user_profile_username_backfill_audit_owner_select on user_profile_username_backfill_audit;
create policy user_profile_username_backfill_audit_owner_select on user_profile_username_backfill_audit
  for select
  using (user_id = current_app_user_id());

create index if not exists idx_user_profile_username_backfill_audit_user
  on user_profile_username_backfill_audit (user_id);

-- ── 2. the backfill ────────────────────────────────────────────────────────────
do $backfill$
declare
  -- Mirrors RESERVED_HANDLES in web/src/app/api/utils/petHandle.js.
  v_reserved constant text[] := array[
    'pawpi','pawpiapp','admin','administrator','moderator','mod','staff','team','support','help',
    'official','security','billing','privacy','terms','legal','about','contact','settings','login',
    'logout','signup','register','search','explore','discover','notifications','messages','feed','home',
    'api','www','root','system','null','undefined','anonymous','deleted','everyone','all','me','you',
    'vet','vets'
  ];
  r            record;
  v_local      text;
  v_lower      text;
  v_derived    boolean;
  v_name       text;
  v_base       text;
  v_cand       text;
  v_new        text;
  v_n          integer;
  v_tries      integer;
  v_renamed    integer := 0;

  -- True when `p` would be classified e-mail-derived for a user whose e-mail local part is `loc`.
  -- (Inline closure replacement: plpgsql has no nested functions, so this is repeated as an expression.)
begin
  for r in
    select up.id, up.username, up.full_name,
           lower(split_part(coalesce(au.email, ''), '@', 1)) as email_local,
           (select p.name from pets p where p.owner_user_id = up.id order by p.id limit 1) as pet_name
    from user_profiles up
    left join auth_users au on au.id = up.auth_user_id
    where up.username is not null
      and up.username not in ('pawpi_welcome', 'pawpi_directory')
    order by up.id
  loop
    v_local := r.email_local;
    v_lower := lower(r.username);

    v_derived :=
         position('@' in r.username) > 0
      or position('+' in r.username) > 0
      or (v_local <> '' and (
            v_lower = v_local
         or (left(v_lower, length(v_local) + 1) = v_local || '_'
             and substr(v_lower, length(v_local) + 2) ~ '^[0-9]{1,13}$')
         ));

    continue when not v_derived;

    -- Base: display name, else first pet's name, else random neutral. Accents folded, a-z0-9 only.
    v_name := coalesce(nullif(btrim(r.full_name), ''), nullif(btrim(r.pet_name), ''), '');
    v_base := lower(translate(v_name,
      'áàäâãåéèëêíìïîóòöôõúùüûñçÁÀÄÂÃÅÉÈËÊÍÌÏÎÓÒÖÔÕÚÙÜÛÑÇ',
      'aaaaaaeeeeiiiiooooouuuuncAAAAAAEEEEIIIIOOOOOUUUUNC'));
    v_base := left(regexp_replace(v_base, '[^a-z0-9]+', '', 'g'), 24);
    if length(v_base) < 3 then
      v_base := null;  -- too short to be a handle -> random neutral below
    end if;

    v_new := null;
    v_n := 1;
    v_tries := 0;
    while v_new is null loop
      v_tries := v_tries + 1;
      if v_base is not null and v_tries <= 999 then
        v_cand := case when v_n = 1 then v_base
                       else left(v_base, 24 - length(v_n::text)) || v_n::text end;
        v_n := v_n + 1;
      else
        v_cand := 'pawpi_' || substr(md5(random()::text || clock_timestamp()::text || r.id::text), 1, 6);
      end if;

      if v_cand = any (v_reserved) then continue; end if;
      -- never produce something that is itself e-mail-derived for THIS user (keeps re-runs a no-op)
      if v_local <> '' and (
           v_cand = v_local
        or (left(v_cand, length(v_local) + 1) = v_local || '_'
            and substr(v_cand, length(v_local) + 2) ~ '^[0-9]{1,13}$')
      ) then continue; end if;
      if exists (select 1 from user_profiles x where lower(x.username) = v_cand and x.id <> r.id) then continue; end if;
      if exists (select 1 from pets p where lower(p.handle) = v_cand) then continue; end if;

      v_new := v_cand;
    end loop;

    insert into user_profile_username_backfill_audit (user_id, old_username, new_username)
    values (r.id, r.username, v_new);

    update user_profiles set username = v_new, updated_at = now() where id = r.id;
    v_renamed := v_renamed + 1;
  end loop;

  raise notice '0133_username_backfill: % username(s) rewritten', v_renamed;
end
$backfill$;
