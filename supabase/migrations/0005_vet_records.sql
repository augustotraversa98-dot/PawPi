create index if not exists idx_pet_lab_results_date on pet_lab_results (test_date desc);
create index if not exists idx_pet_lab_results_owner_user_id on pet_lab_results (owner_user_id);
create index if not exists idx_pet_lab_results_pet_id on pet_lab_results (pet_id);

