create table if not exists vet_documents (
  id            integer generated by default as identity primary key,
  pet_id        integer not null references pets(id) on delete cascade,
  owner_user_id integer not null references user_profiles(id) on delete cascade,
  name          text not null,
  document_type text not null,
  file_url      text not null,
  document_date date,
  notes         text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists idx_vet_documents_date on vet_documents (document_date desc);
create index if not exists idx_vet_documents_owner_user_id on vet_documents (owner_user_id);
create index if not exists idx_vet_documents_pet_id on vet_documents (pet_id);

create table if not exists vet_notes (
  id             integer generated by default as identity primary key,
  pet_id         integer not null references pets(id) on delete cascade,
  owner_user_id  integer not null references user_profiles(id) on delete cascade,
  vet_name       text,
  note_date      date not null,
  note           text not null,
  appointment_id integer references vet_appointments(id) on delete set null,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index if not exists idx_vet_notes_date on vet_notes (note_date desc);
create index if not exists idx_vet_notes_owner_user_id on vet_notes (owner_user_id);
create index if not exists idx_vet_notes_pet_id on vet_notes (pet_id);
