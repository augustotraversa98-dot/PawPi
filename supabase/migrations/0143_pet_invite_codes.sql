-- 0143_pet_invite_codes.sql
-- Family-sharing series PR 6/7 (docs/pr6-invite-code-design.md): invite codes, for a partner who cannot be found by name
-- (e.g. an Apple "Hide My Email" account that has no username yet).
--
-- WHAT
--  1. pet_invite_codes — one row per code the OWNER creates for ONE pet and ONE role. Only sha256(code) is stored: the code
--     is shown once, to the owner, and a database dump holds nothing redeemable. Single use (used_at), expires (at most
--     7 days; the app issues 3), revocable (revoked_at). ENABLE + FORCE RLS: only the owner can see, create or revoke
--     their codes; there is NO delete policy (history is kept) and no way for anyone else to read the table.
--  2. app_redeem_pet_invite(code_hash) — SECURITY DEFINER, the only way a non-owner touches a code. It locks the row
--     (two people redeeming at once: one wins), refuses unknown / revoked / used / expired codes, blocked pairs, the
--     owner themselves and people who already have access, then creates (or activates) the caller's ACTIVE grant,
--     burns the code and writes the audit rows. Redeeming IS accepting: the owner's consent is the code they handed over.
--
-- IDEMPOTENT. HAND-APPLIED: supabase/verify_0143.sql (every row PASS); rollback: supabase/rollback_0143.sql.
-- Without it the API answers a friendly 503 `invite_codes_unavailable`; everything else is unchanged.

create table if not exists pet_invite_codes (
  id               integer generated by default as identity primary key,
  pet_id           integer not null references pets(id) on delete cascade,
  owner_user_id    integer not null references user_profiles(id) on delete cascade,
  role             text not null,
  code_hash        text not null,
  expires_at       timestamptz not null,
  used_at          timestamptz,
  used_by_user_id  integer references user_profiles(id) on delete set null,
  grant_id         integer references pet_caregivers(id) on delete set null,
  revoked_at       timestamptz,
  created_at       timestamptz not null default now(),
  constraint pet_invite_codes_role_check check (role = any (array['family','caregiver']::text[])),
  constraint pet_invite_codes_hash_check check (code_hash ~ '^[0-9a-f]{64}$'),
  constraint pet_invite_codes_expiry_check
    check (expires_at > created_at and expires_at <= created_at + interval '7 days')
);

create unique index if not exists idx_pet_invite_codes_hash on pet_invite_codes (code_hash);
create index if not exists idx_pet_invite_codes_pet on pet_invite_codes (pet_id, owner_user_id);
create index if not exists idx_pet_invite_codes_owner on pet_invite_codes (owner_user_id);
create index if not exists idx_pet_invite_codes_used_by on pet_invite_codes (used_by_user_id);
create index if not exists idx_pet_invite_codes_grant on pet_invite_codes (grant_id);

alter table pet_invite_codes enable row level security;
alter table pet_invite_codes force row level security;

drop policy if exists pet_invite_codes_owner_select on pet_invite_codes;
create policy pet_invite_codes_owner_select on pet_invite_codes
  for select using (owner_user_id = current_app_user_id());

drop policy if exists pet_invite_codes_owner_insert on pet_invite_codes;
create policy pet_invite_codes_owner_insert on pet_invite_codes
  for insert with check (
    owner_user_id = current_app_user_id()
    and app_owns_pet(pet_id)
    and used_at is null and used_by_user_id is null and grant_id is null and revoked_at is null
  );

drop policy if exists pet_invite_codes_owner_update on pet_invite_codes;
create policy pet_invite_codes_owner_update on pet_invite_codes
  for update
  using (owner_user_id = current_app_user_id())
  with check (owner_user_id = current_app_user_id() and app_owns_pet(pet_id));

create or replace function app_redeem_pet_invite(p_code_hash text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid      integer := current_app_user_id();
  c          pet_invite_codes;
  g          pet_caregivers;
  v_pet_name text;
  v_grant    integer;
  v_scopes   text[];
begin
  if v_uid is null then
    raise exception 'no identity';
  end if;

  select * into c from pet_invite_codes where code_hash = p_code_hash for update;
  -- A blocked pair learns nothing: the code simply does not work.
  if not found or app_user_is_blocked(v_uid, c.owner_user_id) then
    return jsonb_build_object('result', 'invalid');
  end if;
  if c.owner_user_id = v_uid then
    return jsonb_build_object('result', 'own_pet');
  end if;
  if c.used_at is not null then
    -- The same person tapping twice is told they are in, not that someone else took it.
    if c.used_by_user_id = v_uid then
      return jsonb_build_object('result', 'already_member', 'pet_id', c.pet_id);
    end if;
    return jsonb_build_object('result', 'used');
  end if;
  if c.revoked_at is not null then
    return jsonb_build_object('result', 'revoked');
  end if;
  if c.expires_at <= now() then
    return jsonb_build_object('result', 'expired');
  end if;

  -- The issuer must still own the pet.
  select name into v_pet_name from pets where id = c.pet_id and owner_user_id = c.owner_user_id;
  if not found then
    return jsonb_build_object('result', 'invalid');
  end if;

  v_scopes := case when c.role = 'family'
                   then array['profile','routines','health','medical']
                   else array['profile','routines','medical'] end;

  select * into g from pet_caregivers
    where pet_id = c.pet_id and grantee_user_id = v_uid and status in ('pending', 'active')
    for update;
  if found then
    if g.status = 'active' and (g.expires_at is null or g.expires_at > now()) then
      -- Already has access: nothing changes and the code stays usable.
      return jsonb_build_object('result', 'already_member', 'pet_id', c.pet_id);
    end if;
    update pet_caregivers
      set status = 'active', role = c.role, scopes = v_scopes, expires_at = null,
          accepted_at = now(), updated_at = now()
      where id = g.id;
    v_grant := g.id;
  else
    insert into pet_caregivers (pet_id, owner_user_id, grantee_user_id, role, scopes, status, accepted_at)
      values (c.pet_id, c.owner_user_id, v_uid, c.role, v_scopes, 'active', now())
      returning id into v_grant;
  end if;

  update pet_invite_codes
    set used_at = now(), used_by_user_id = v_uid, grant_id = v_grant
    where id = c.id;

  insert into pet_caregiver_audit (grant_id, owner_user_id, actor_user_id, action)
    values (v_grant, c.owner_user_id, c.owner_user_id, 'grant'),
           (v_grant, c.owner_user_id, v_uid, 'accept');

  return jsonb_build_object(
    'result', 'ok', 'pet_id', c.pet_id, 'pet_name', v_pet_name, 'role', c.role,
    'owner_user_id', c.owner_user_id, 'grant_id', v_grant
  );
end;
$$;

revoke execute on function app_redeem_pet_invite(text) from public;
do $$
declare r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke execute on function app_redeem_pet_invite(text) from %I', r);
      execute format('revoke all on table pet_invite_codes from %I', r);
    end if;
  end loop;
end
$$;
grant execute on function app_redeem_pet_invite(text) to pawpi_app;
