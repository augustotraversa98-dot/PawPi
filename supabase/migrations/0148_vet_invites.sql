-- 0148_vet_invites.sql
-- Inviting a vet by link (docs/vet-sharing-design.md, "Invite by link").
--
-- WHAT
--  1. care_access_invites: one row per link the OWNER creates for ONE pet. Only sha256(token) is stored. A link
--     expires (at most 7 days), works once (used_at) and can be revoked (revoked_at). ENABLE + FORCE RLS: only the owner
--     reads, creates or revokes their invites; there is no delete policy.
--  2. app_can_accept_vet_invite: the caller is active staff of that published business with the 'vet' capability.
--  3. app_preview_vet_invite: for such a caller and a usable invite, the pet's name, the owner's display name and the
--     expiry. Nothing else, and no row otherwise.
--  4. app_claim_vet_invite: marks a usable invite as used by one business. It creates no grant: the route then inserts
--     the PENDING request through the existing care_access_grants insert policy, in the same transaction.
--  5. notifications_type_check gains care_access_requested.
--
-- Accepting an invite opens nothing. The vet sees the record only after the owner approves the pending request.
--
-- ADDITIVE and IDEMPOTENT. No row is changed or deleted, no existing policy or function is replaced, and the server
-- deployed before this migration keeps working with it. HAND-APPLIED before the matching server code is deployed; then
-- run supabase/verify_0148.sql (every row PASS).

-- ── 1. the table ───────────────────────────────────────────────────────────────────────────────────────────────
create table if not exists care_access_invites (
  id                   integer generated by default as identity primary key,
  pet_id               integer not null references pets(id) on delete cascade,
  owner_user_id        integer not null references user_profiles(id) on delete cascade,
  token_hash           text not null,
  expires_at           timestamptz not null,
  used_at              timestamptz,
  used_by_user_id      integer references user_profiles(id) on delete set null,
  used_by_provider_id  integer references providers(id) on delete set null,
  revoked_at           timestamptz,
  created_at           timestamptz not null default now(),
  constraint care_access_invites_hash_check check (token_hash ~ '^[0-9a-f]{64}$'),
  constraint care_access_invites_expiry_check
    check (expires_at > created_at and expires_at <= created_at + interval '7 days')
);

create unique index if not exists idx_care_access_invites_hash on care_access_invites (token_hash);
create index if not exists idx_care_access_invites_owner on care_access_invites (owner_user_id);
create index if not exists idx_care_access_invites_pet on care_access_invites (pet_id);
create index if not exists idx_care_access_invites_used_by_user on care_access_invites (used_by_user_id);
create index if not exists idx_care_access_invites_used_by_provider on care_access_invites (used_by_provider_id);

alter table care_access_invites enable row level security;
alter table care_access_invites force row level security;

drop policy if exists care_access_invites_owner_select on care_access_invites;
create policy care_access_invites_owner_select on care_access_invites
  for select
  using (owner_user_id = current_app_user_id());

drop policy if exists care_access_invites_owner_insert on care_access_invites;
create policy care_access_invites_owner_insert on care_access_invites
  for insert
  with check (
    owner_user_id = current_app_user_id()
    and app_owns_pet(pet_id)
    and used_at is null
    and used_by_user_id is null
    and used_by_provider_id is null
    and revoked_at is null
  );

drop policy if exists care_access_invites_owner_update on care_access_invites;
create policy care_access_invites_owner_update on care_access_invites
  for update
  using (owner_user_id = current_app_user_id())
  with check (owner_user_id = current_app_user_id() and revoked_at is not null);

-- ── 2. who may accept ──────────────────────────────────────────────────────────────────────────────────────────
create or replace function app_can_accept_vet_invite(p_provider_id integer)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select app_is_active_staff_of(p_provider_id)
    and exists (select 1 from providers pr where pr.id = p_provider_id and pr.status = 'published')
    and exists (select 1 from provider_capabilities pc where pc.provider_id = p_provider_id and pc.capability = 'vet')
$$;

-- ── 3. the little an invited vet sees ──────────────────────────────────────────────────────────────────────────
create or replace function app_preview_vet_invite(p_token_hash text)
returns table (pet_name text, owner_name text, expires_at timestamptz)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select p.name::text, nullif(btrim(o.full_name), '')::text, i.expires_at
  from care_access_invites i
  join pets p
    on p.id = i.pet_id and p.owner_user_id = i.owner_user_id
  join user_profiles o
    on o.id = i.owner_user_id
  where i.token_hash = p_token_hash
    and i.used_at is null
    and i.revoked_at is null
    and i.expires_at > now()
    and exists (
      select 1 from provider_staff ps
      where ps.user_profile_id = current_app_user_id()
        and app_can_accept_vet_invite(ps.provider_id)
    )
    and not app_user_is_blocked(current_app_user_id(), i.owner_user_id)
$$;

-- ── 4. using an invite, once ───────────────────────────────────────────────────────────────────────────────────
create or replace function app_claim_vet_invite(p_token_hash text, p_provider_id integer)
returns table (pet_id integer, owner_user_id integer, pet_name text)
language sql
volatile
security definer
set search_path = public, pg_temp
as $$
  update care_access_invites i
  set used_at = now(),
      used_by_user_id = current_app_user_id(),
      used_by_provider_id = p_provider_id
  from pets p
  where i.token_hash = p_token_hash
    and p.id = i.pet_id
    and p.owner_user_id = i.owner_user_id
    and i.used_at is null
    and i.revoked_at is null
    and i.expires_at > now()
    and app_can_accept_vet_invite(p_provider_id)
    and not app_user_is_blocked(current_app_user_id(), i.owner_user_id)
  returning i.pet_id, i.owner_user_id, p.name::text
$$;

-- ── privileges ─────────────────────────────────────────────────────────────────────────────────────────────────
revoke execute on function app_can_accept_vet_invite(integer) from public;
revoke execute on function app_preview_vet_invite(text) from public;
revoke execute on function app_claim_vet_invite(text, integer) from public;
revoke all on table care_access_invites from public;
do $$
declare r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke execute on function app_can_accept_vet_invite(integer) from %I', r);
      execute format('revoke execute on function app_preview_vet_invite(text) from %I', r);
      execute format('revoke execute on function app_claim_vet_invite(text, integer) from %I', r);
      execute format('revoke all on table care_access_invites from %I', r);
      execute format('revoke all on sequence care_access_invites_id_seq from %I', r);
    end if;
  end loop;
end
$$;
grant execute on function app_can_accept_vet_invite(integer) to pawpi_app;
grant execute on function app_preview_vet_invite(text) to pawpi_app;
grant execute on function app_claim_vet_invite(text, integer) to pawpi_app;
grant select, insert, update on table care_access_invites to pawpi_app;

