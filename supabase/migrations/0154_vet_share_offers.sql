-- 0154_vet_share_offers.sql
-- Inviting a vet that is on PawPi directly (docs/vet-sharing-design.md, "Invitations to a vet on PawPi").
--
-- WHAT
--  1. care_share_offers: one row per invitation the OWNER sends to ONE business for ONE pet, with the parts of the
--     record and the length they chose. It opens nothing. At most one unanswered invitation per business and pet
--     (unique index), and it lapses after 7 days. ENABLE + FORCE RLS: only the owner reads, creates and withdraws their
--     invitations; there is no delete policy and no staff policy.
--  2. app_vet_can_receive_share / app_search_share_vets: the published vet businesses an owner can find and invite, with
--     public business fields only.
--  3. app_provider_share_offers: for active staff of an invited business, the unanswered invitations with the pet's name,
--     the owner's display name, the parts and the length. Nothing from the record.
--  4. app_respond_share_offer: active staff accept or decline. Accepting creates (or replaces) the grant by section with
--     exactly the offered parts and length, the length starting now. Accepting twice changes nothing.
--  5. app_lapse_share_offers closes invitations past their date or whose pet changed owner.
--  6. A later decision of the owner about that business's access (sharing, approving, denying or revoking) withdraws the
--     unanswered invitation (trigger on care_access_grants), so accepting can never undo it.
--  7. notifications_type_check gains care_share_offered, care_share_accepted and care_share_declined.
--
-- No existing policy, grant status or function is changed: access only ever starts as an ordinary care_access_grants row.
-- The one addition on that table is the trigger of point 6, which writes only to care_share_offers.
--
-- ADDITIVE and IDEMPOTENT. No row is changed or deleted, and the server deployed before this migration keeps working
-- with it (the new server also works without it and reports invitations as not available).
-- HAND-APPLIED after merge; then run supabase/verify_0154.sql (every row PASS).

-- ── 1. the table ───────────────────────────────────────────────────────────────────────────────────────────────
create table if not exists care_share_offers (
  id                    integer generated by default as identity primary key,
  pet_id                integer not null references pets(id) on delete cascade,
  owner_user_id         integer not null references user_profiles(id) on delete cascade,
  provider_id           integer not null references providers(id) on delete cascade,
  sections              text[] not null,
  duration              text not null,
  status                text not null default 'open',
  created_at            timestamptz not null default now(),
  lapses_at             timestamptz not null default (now() + interval '7 days'),
  responded_at          timestamptz,
  responded_by_user_id  integer references user_profiles(id) on delete set null,
  grant_id              integer references care_access_grants(id) on delete set null,
  constraint care_share_offers_sections_check check (
    cardinality(sections) > 0
    and array_position(sections, null) is null
    and sections <@ array['profile','emergency_contact','insurance','vet_notes','vaccines','files','photos','lab_results']::text[]
  ),
  constraint care_share_offers_duration_check check (duration in ('7d', '30d', '1y', 'until_revoked')),
  constraint care_share_offers_status_check check (status in ('open', 'accepted', 'declined', 'withdrawn', 'lapsed')),
  constraint care_share_offers_lapse_check
    check (lapses_at > created_at and lapses_at <= created_at + interval '7 days')
);

create unique index if not exists idx_care_share_offers_open
  on care_share_offers (provider_id, pet_id) where status = 'open';
create index if not exists idx_care_share_offers_owner on care_share_offers (owner_user_id);
create index if not exists idx_care_share_offers_pet on care_share_offers (pet_id);
create index if not exists idx_care_share_offers_provider on care_share_offers (provider_id);
create index if not exists idx_care_share_offers_responded_by on care_share_offers (responded_by_user_id);
create index if not exists idx_care_share_offers_grant on care_share_offers (grant_id);

alter table care_share_offers enable row level security;
alter table care_share_offers force row level security;

-- ── 2. which businesses can be invited ─────────────────────────────────────────────────────────────────────────
-- A published, non-demo business with the 'vet' capability that is not an unclaimed directory listing and has an active
-- team member with an account that can receive the invitation; never one the caller blocked, or that blocked them.
-- claim_status is read through to_jsonb so the function also works on a database without that column.
create or replace function app_vet_can_receive_share(p_provider_id integer)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from providers pr
    where pr.id = p_provider_id
      and pr.status = 'published'
      and pr.is_demo is not true
      and (to_jsonb(pr) ->> 'claim_status') is distinct from 'unclaimed'
      and exists (select 1 from provider_capabilities pc where pc.provider_id = pr.id and pc.capability = 'vet')
      and exists (
        select 1
        from provider_staff ps
        join user_profiles u on u.id = ps.user_profile_id
        join auth_users a on a.id = u.auth_user_id
        where ps.provider_id = pr.id and ps.status = 'active' and u.banned_at is null
      )
      and not app_user_is_blocked(current_app_user_id(), pr.owner_user_profile_id)
  )
$$;

-- Search by part of the business name or handle (slug), or by the owning account's username typed in full.
-- Public business fields only: nothing about the account.
create or replace function app_search_share_vets(p_query text)
returns table (id integer, name text, handle text, logo_url text, location_name text, address text)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with q as (
    select lower(btrim(coalesce(p_query, ''))) as raw,
           replace(replace(replace(lower(btrim(coalesce(p_query, ''))), '\', '\\'), '%', '\%'), '_', '\_') as needle
  )
  select pr.id, pr.name::text, pr.slug::text, pr.logo_url::text, loc.name::text, loc.address::text
  from q
  join providers pr
    on length(q.raw) between 2 and 60
   and (
     lower(pr.name) like '%' || q.needle || '%'
     or lower(pr.slug) like '%' || q.needle || '%'
     or exists (
           select 1 from user_profiles o
           where o.id = pr.owner_user_profile_id and lower(o.username) = q.raw)
   )
  left join lateral (
    select pl.name, pl.address from provider_locations pl where pl.provider_id = pr.id order by pl.id limit 1
  ) loc on true
  where current_app_user_id() is not null
    and app_vet_can_receive_share(pr.id)
  order by (lower(pr.name) = q.raw or lower(pr.slug) = q.raw) desc, pr.name, pr.id
  limit 20
$$;

-- ── owner policies (after the helper they use) ─────────────────────────────────────────────────────────────────
drop policy if exists care_share_offers_owner_select on care_share_offers;
create policy care_share_offers_owner_select on care_share_offers
  for select
  using (owner_user_id = current_app_user_id());

drop policy if exists care_share_offers_owner_insert on care_share_offers;
create policy care_share_offers_owner_insert on care_share_offers
  for insert
  with check (
    owner_user_id = current_app_user_id()
    and app_owns_pet(pet_id)
    and app_vet_can_receive_share(provider_id)
    and status = 'open'
    and responded_at is null
    and responded_by_user_id is null
    and grant_id is null
  );

-- The only change an owner makes: withdraw an unanswered invitation (or close one past its date).
drop policy if exists care_share_offers_owner_update on care_share_offers;
create policy care_share_offers_owner_update on care_share_offers
  for update
  using (owner_user_id = current_app_user_id() and status = 'open')
  with check (owner_user_id = current_app_user_id() and status in ('withdrawn', 'lapsed') and grant_id is null);

-- ── 3. what an invited business sees before answering ──────────────────────────────────────────────────────────
create or replace function app_provider_share_offers(p_provider_id integer)
returns table (
  id          integer,
  pet_name    text,
  owner_name  text,
  sections    text[],
  duration    text,
  created_at  timestamptz,
  lapses_at   timestamptz
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select o.id,
         p.name::text,
         -- An e-mail address is never shown as a name.
         case when position('@' in u.full_name) = 0 then nullif(btrim(u.full_name), '')::text end,
         o.sections,
         o.duration,
         o.created_at,
         o.lapses_at
  from care_share_offers o
  join pets p on p.id = o.pet_id and p.owner_user_id = o.owner_user_id
  join user_profiles u on u.id = o.owner_user_id
  where o.provider_id = p_provider_id
    and app_can_accept_vet_invite(p_provider_id)
    and o.status = 'open'
    and o.lapses_at > now()
    and not app_user_is_blocked(current_app_user_id(), o.owner_user_id)
    and not app_user_is_blocked(
      o.owner_user_id, (select pr.owner_user_profile_id from providers pr where pr.id = o.provider_id))
  order by o.created_at desc, o.id desc
$$;

-- ── 4. answering ───────────────────────────────────────────────────────────────────────────────────────────────
-- outcome: 'accepted' | 'declined' (this call answered it) · 'already_accepted' | 'already_declined' (the same answer
-- was given before: nothing changes) · 'not_open' (answered otherwise, withdrawn, lapsed, blocked or the pet changed
-- owner) · 'not_found' (not an invitation of this business, or the caller is not its active staff) · 'not_eligible'
-- (accepting needs a published business with the vet capability).
-- The other columns describe the invitation for the outcomes that name one.
create or replace function app_respond_share_offer(p_offer_id integer, p_provider_id integer, p_accept boolean)
returns table (outcome text, pet integer, owner integer, pet_name text, access_expires_at timestamptz)
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_offer     care_share_offers%rowtype;
  v_pet_id    integer;
  v_pet_name  text;
  v_pet_owner integer;
  v_length    interval;
  v_grant     integer;
  v_expires   timestamptz;
begin
  if p_accept is null or not app_is_active_staff_of(p_provider_id) then
    return query select 'not_found'::text, null::integer, null::integer, null::text, null::timestamptz;
    return;
  end if;

  select o.pet_id into v_pet_id
  from care_share_offers o
  where o.id = p_offer_id and o.provider_id = p_provider_id;
  if v_pet_id is null then
    return query select 'not_found'::text, null::integer, null::integer, null::text, null::timestamptz;
    return;
  end if;

  -- One change at a time per pet and business: the lock the owner's own share takes, then the invitation.
  perform pg_advisory_xact_lock(hashtext('care_access_grant:' || v_pet_id || ':' || p_provider_id));
  -- The open access first, then the invitation: the same order in which a change to the access reaches them.
  perform 1 from care_access_grants g
  where g.pet_id = v_pet_id and g.provider_id = p_provider_id and g.status in ('pending', 'active')
  for update;
  select o.* into v_offer
  from care_share_offers o
  where o.id = p_offer_id and o.provider_id = p_provider_id
  for update;

  select p.name::text, p.owner_user_id into v_pet_name, v_pet_owner from pets p where p.id = v_offer.pet_id;

  if (v_offer.status = 'accepted' and p_accept) or (v_offer.status = 'declined' and not p_accept) then
    select g.expires_at into v_expires from care_access_grants g where g.id = v_offer.grant_id;
    return query select ('already_' || v_offer.status)::text, v_offer.pet_id, v_offer.owner_user_id, v_pet_name, v_expires;
    return;
  end if;

  if v_offer.status = 'open'
     and (v_offer.lapses_at <= now() or v_pet_owner is distinct from v_offer.owner_user_id) then
    update care_share_offers o set status = 'lapsed' where o.id = v_offer.id;
    v_offer.status := 'lapsed';
  end if;
  if v_offer.status <> 'open'
     or app_user_is_blocked(current_app_user_id(), v_offer.owner_user_id)
     or app_user_is_blocked(
          v_offer.owner_user_id, (select pr.owner_user_profile_id from providers pr where pr.id = p_provider_id)) then
    return query select 'not_open'::text, null::integer, null::integer, null::text, null::timestamptz;
    return;
  end if;

  if not p_accept then
    update care_share_offers o
    set status = 'declined', responded_at = now(), responded_by_user_id = current_app_user_id()
    where o.id = v_offer.id;
    return query select 'declined'::text, v_offer.pet_id, v_offer.owner_user_id, v_pet_name, null::timestamptz;
    return;
  end if;

  if not app_can_accept_vet_invite(p_provider_id) then
    return query select 'not_eligible'::text, null::integer, null::integer, null::text, null::timestamptz;
    return;
  end if;

  v_length := case v_offer.duration
                when '7d' then interval '7 days'
                when '30d' then interval '30 days'
                when '1y' then interval '1 year'
              end; -- null: until the owner revokes
  v_expires := now() + v_length;

  -- Answered first: the grant changes below must not read this invitation as one the owner has since replaced.
  update care_share_offers o
  set status = 'accepted', responded_at = now(), responded_by_user_id = current_app_user_id()
  where o.id = v_offer.id;

  -- The same steps the owner's own share takes: close what is past its date, end the access in place, then answer a
  -- pending request or create the grant, with exactly the offered parts. A previous owner's open row ends too.
  update care_access_grants g
  set status = 'expired', updated_at = now()
  where g.pet_id = v_offer.pet_id and g.provider_id = p_provider_id
    and g.status in ('pending', 'active') and g.expires_at <= now();
  update care_access_grants g
  set status = 'revoked', revoked_at = now(), updated_at = now()
  where g.pet_id = v_offer.pet_id and g.provider_id = p_provider_id
    and (g.status = 'active' or (g.status = 'pending' and g.owner_user_id <> v_offer.owner_user_id));

  for attempt in 1..2 loop
    update care_access_grants g
    set status = 'active', scopes = array['record_sections']::text[], sections = v_offer.sections,
        expires_at = v_expires, granted_at = now(), updated_at = now()
    where g.pet_id = v_offer.pet_id and g.provider_id = p_provider_id
      and g.owner_user_id = v_offer.owner_user_id and g.status = 'pending'
    returning g.id into v_grant;
    exit when v_grant is not null;
    begin
      insert into care_access_grants (
        pet_id, owner_user_id, provider_id, scopes, sections, status, requested_by, granted_at, expires_at
      ) values (
        v_offer.pet_id, v_offer.owner_user_id, p_provider_id, array['record_sections']::text[], v_offer.sections,
        'active', 'owner', now(), v_expires
      )
      returning care_access_grants.id into v_grant;
    exception when unique_violation then
      -- The business's own request arrived meanwhile: answer it on the next pass.
      v_grant := null;
    end;
    exit when v_grant is not null;
  end loop;
  if v_grant is null then
    raise exception 'app_respond_share_offer: could not create the access';
  end if;

  update care_share_offers o set grant_id = v_grant where o.id = v_offer.id;

  return query select 'accepted'::text, v_offer.pet_id, v_offer.owner_user_id, v_pet_name, v_expires;
end
$$;

-- ── 5. closing invitations that can no longer be answered ──────────────────────────────────────────────────────
-- For the pet's current owner or the business's active staff; only rows past their date or from a previous owner (they
-- can already not be accepted). Returns how many it closed. DEFINER because a new owner cannot see the old row.
create or replace function app_lapse_share_offers(p_pet_id integer, p_provider_id integer)
returns integer
language sql
volatile
security definer
set search_path = public, pg_temp
as $$
  with closed as (
    update care_share_offers o
    set status = 'lapsed'
    from pets p
    where o.pet_id = p_pet_id
      and o.provider_id = p_provider_id
      and o.status = 'open'
      and p.id = o.pet_id
      and (o.lapses_at <= now() or p.owner_user_id <> o.owner_user_id)
      and (p.owner_user_id = current_app_user_id() or app_is_active_staff_of(o.provider_id))
    returning 1
  )
  select count(*)::integer from closed
$$;

-- ── 6. the owner's later decision wins ─────────────────────────────────────────────────────────────────────────
-- Any time access for a pet and business starts, is approved, is denied or is revoked, an unanswered invitation to that
-- business is withdrawn. DEFINER because the change may be made by an identity without update rights on the invitation.
create or replace function app_close_superseded_share_offers()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if (tg_op = 'INSERT' and new.status = 'active')
     or (tg_op = 'UPDATE' and (new.granted_at is distinct from old.granted_at
                               or new.revoked_at is distinct from old.revoked_at)) then
    update care_share_offers o
    set status = 'withdrawn', responded_at = now()
    where o.pet_id = new.pet_id
      and o.provider_id = new.provider_id
      and o.owner_user_id = new.owner_user_id
      and o.status = 'open';
  end if;
  return null;
end
$$;

drop trigger if exists care_access_grants_close_share_offers on care_access_grants;
create trigger care_access_grants_close_share_offers
  after insert or update of granted_at, revoked_at on care_access_grants
  for each row execute function app_close_superseded_share_offers();

