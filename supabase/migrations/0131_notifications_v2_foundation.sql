-- 0131_notifications_v2_foundation.sql
-- Notifications v2, PR 3a (docs/notifications-v2-design.md, docs/notifications-audit.md §3-§4).
--
-- WHAT THIS ADDS (all ADDITIVE; no existing table's RLS or policy is touched):
--   1. device_push_tokens += invalid_since / last_seen  — so a token Expo reports as dead
--      (DeviceNotRegistered) is skipped instead of retried forever.
--   2. push_tickets          — one row per Expo push ticket, so the receipts job can find out later
--      (>= 15 min) whether delivery failed and prune the dead token.
--   3. notification_send_log — one row per push/email attempt: the dedupe / analytics / per-user DAILY
--      CAP source of truth the audit found missing (finding 3, "no send log").
--   4. SECURITY DEFINER helpers — the app writes these cross-owner (the sender runs as the ACTOR or with
--      no identity at all, never as the recipient), so the tables have NO write policy:
--        app_recipient_valid_push_tokens, app_mark_push_token_invalid, app_record_push_ticket,
--        app_pending_push_tickets, app_resolve_push_tickets,
--        app_user_day_start, app_notification_sends_today, app_reserve_notification_send,
--        app_log_notification_send, app_notification_send_log_gc, app_set_email_consent.
--
-- NOTHING CALLS THESE UNTIL THE SERVER FLAG NOTIF_V2_ENABLED IS ON. The code that uses them wraps every call
-- in a savepoint + try/catch and degrades to today's behaviour on 42P01 / 42883 / 42703, so merging the PR
-- before this migration is applied changes nothing in production.
--
-- RLS: both new tables are ENABLE + FORCE with an own-row SELECT policy only
-- (owner_user_id = current_app_user_id(); NULL identity => deny). There is deliberately NO INSERT / UPDATE /
-- DELETE policy: pawpi_app can never forge or erase its own send history (same stance as rate_limit_hits,
-- 0113). The DEFINER helpers below are the only writers.
--
-- Idempotent (IF NOT EXISTS / CREATE OR REPLACE / drop-if-exists + re-add). Human-applied: verify with
-- supabase/verify_0131.sql (every row must read PASS).

-- ── 1. device_push_tokens: invalid_since + last_seen ──────────────────────────
alter table device_push_tokens
  add column if not exists invalid_since timestamptz,
  add column if not exists last_seen     timestamptz;

create index if not exists idx_device_push_tokens_token on device_push_tokens (token);

-- ── 2. push_tickets: Expo ticket id per send, for the receipts job ────────────
create table if not exists push_tickets (
  id             bigint generated by default as identity primary key,
  owner_user_id  integer     not null references user_profiles(id) on delete cascade,
  token          text        not null,
  ticket_id      text        not null,
  created_at     timestamptz not null default now(),
  checked_at     timestamptz,
  constraint push_tickets_ticket_id_key unique (ticket_id)
);

create index if not exists idx_push_tickets_pending
  on push_tickets (created_at) where checked_at is null;
create index if not exists idx_push_tickets_owner
  on push_tickets (owner_user_id);

alter table push_tickets enable row level security;
alter table push_tickets force  row level security;

drop policy if exists push_tickets_owner_select on push_tickets;
create policy push_tickets_owner_select on push_tickets
  for select
  using (owner_user_id = current_app_user_id());

-- ── 3. notification_send_log ──────────────────────────────────────────────────
create table if not exists notification_send_log (
  id             bigint generated by default as identity primary key,
  owner_user_id  integer     not null references user_profiles(id) on delete cascade,
  type           text        not null,
  category       text,
  channel        text        not null,
  outcome        text        not null default 'sent',
  subject_ref    text,
  sent_at        timestamptz not null default now(),
  constraint notification_send_log_channel_check
    check (channel in ('push', 'email')),
  constraint notification_send_log_outcome_check
    check (outcome in ('sent', 'suppressed_cap', 'suppressed_quiet', 'suppressed_pref'))
);

create index if not exists idx_notification_send_log_owner_sent
  on notification_send_log (owner_user_id, sent_at desc);
create index if not exists idx_notification_send_log_sent_at
  on notification_send_log (sent_at);

alter table notification_send_log enable row level security;
alter table notification_send_log force  row level security;

drop policy if exists notification_send_log_owner_select on notification_send_log;
create policy notification_send_log_owner_select on notification_send_log
  for select
  using (owner_user_id = current_app_user_id());

-- ── 4a. valid-token reader (skips tokens Expo reported dead) ──────────────────
-- Same shape as app_recipient_push_tokens (0109), which stays untouched so the flag-OFF path is byte-for-byte
-- what runs today.
create or replace function app_recipient_valid_push_tokens(p_user_id integer)
returns table (token text, platform text)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select token, platform
  from device_push_tokens
  where user_id = p_user_id
    and invalid_since is null;
$$;

grant execute on function app_recipient_valid_push_tokens(integer) to pawpi_app;

-- ── 4b. mark a token dead (the same token can sit under several users) ────────
create or replace function app_mark_push_token_invalid(p_token text)
returns integer
language sql
security definer
set search_path = public, pg_temp
as $$
  with u as (
    update device_push_tokens
       set invalid_since = now()
     where token = p_token
       and invalid_since is null
    returning 1
  )
  select count(*)::integer from u;
$$;

grant execute on function app_mark_push_token_invalid(text) to pawpi_app;

-- ── 4c. ticket bookkeeping for the receipts job ───────────────────────────────
create or replace function app_record_push_ticket(
  p_user_id   integer,
  p_token     text,
  p_ticket_id text
)
returns void
language sql
security definer
set search_path = public, pg_temp
as $$
  insert into push_tickets (owner_user_id, token, ticket_id)
  select p_user_id, p_token, p_ticket_id
  where p_user_id is not null
    and p_token is not null
    and p_ticket_id is not null
    and exists (select 1 from user_profiles where id = p_user_id)
  on conflict (ticket_id) do nothing;
$$;

grant execute on function app_record_push_ticket(integer, text, text) to pawpi_app;

create or replace function app_pending_push_tickets(
  p_min_age_seconds integer,
  p_limit           integer
)
returns table (
  id            bigint,
  owner_user_id integer,
  token         text,
  ticket_id     text,
  created_at    timestamptz
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select t.id, t.owner_user_id, t.token, t.ticket_id, t.created_at
  from push_tickets t
  where t.checked_at is null
    and t.created_at <= now() - make_interval(secs => greatest(coalesce(p_min_age_seconds, 0), 0))
  order by t.id
  limit least(greatest(coalesce(p_limit, 500), 1), 5000);
$$;

grant execute on function app_pending_push_tickets(integer, integer) to pawpi_app;

create or replace function app_resolve_push_tickets(p_ids bigint[])
returns integer
language sql
security definer
set search_path = public, pg_temp
as $$
  with u as (
    update push_tickets
       set checked_at = now()
     where id = any(p_ids)
       and checked_at is null
    returning 1
  )
  select count(*)::integer from u;
$$;

grant execute on function app_resolve_push_tickets(bigint[]) to pawpi_app;

-- ── 4d. owner-local day + per-user daily cap ──────────────────────────────────
-- Start (as a timestamptz) of the recipient's CURRENT local day, from user_profiles.timezone (0094) with the
-- app-wide America/Buenos_Aires fallback. An unknown / unusable zone string falls back too rather than raising.
create or replace function app_user_day_start(p_user_id integer)
returns timestamptz
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_tz  text;
  v_out timestamptz;
begin
  select coalesce(timezone, 'America/Buenos_Aires') into v_tz
    from user_profiles where id = p_user_id;
  v_tz := coalesce(v_tz, 'America/Buenos_Aires');
  begin
    v_out := date_trunc('day', now() at time zone v_tz) at time zone v_tz;
  exception when others then
    v_out := date_trunc('day', now() at time zone 'America/Buenos_Aires') at time zone 'America/Buenos_Aires';
  end;
  return v_out;
end;
$$;

grant execute on function app_user_day_start(integer) to pawpi_app;

create or replace function app_notification_sends_today(
  p_user_id integer,
  p_channel text default 'push'
)
returns integer
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select count(*)::integer
  from notification_send_log l
  where l.owner_user_id = p_user_id
    and l.channel = p_channel
    and l.outcome = 'sent'
    and l.sent_at >= app_user_day_start(p_user_id);
$$;

grant execute on function app_notification_sends_today(integer, text) to pawpi_app;

-- Atomic "may I send one more today?": serialises per user with a transaction advisory lock, counts today's
-- SENT rows for the channel, and either records the send (true) or records a 'suppressed_cap' row (false).
-- p_cap NULL = no cap, just log the send. Callers must check tokens / prefs / quiet hours FIRST so a slot is
-- only spent on a notification that will really be attempted.
create or replace function app_reserve_notification_send(
  p_user_id     integer,
  p_type        text,
  p_category    text,
  p_channel     text,
  p_subject_ref text,
  p_cap         integer
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_count integer;
begin
  if p_user_id is null or p_channel not in ('push', 'email') then
    return false;
  end if;
  if not exists (select 1 from user_profiles where id = p_user_id) then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtextextended('notification_send:' || p_user_id::text, 0));

  if p_cap is not null then
    select count(*)::integer into v_count
      from notification_send_log l
     where l.owner_user_id = p_user_id
       and l.channel = p_channel
       and l.outcome = 'sent'
       and l.sent_at >= app_user_day_start(p_user_id);
    if v_count >= p_cap then
      insert into notification_send_log (owner_user_id, type, category, channel, outcome, subject_ref)
      values (p_user_id, p_type, p_category, p_channel, 'suppressed_cap', p_subject_ref);
      return false;
    end if;
  end if;

  insert into notification_send_log (owner_user_id, type, category, channel, outcome, subject_ref)
  values (p_user_id, p_type, p_category, p_channel, 'sent', p_subject_ref);
  return true;
end;
$$;

grant execute on function app_reserve_notification_send(integer, text, text, text, text, integer) to pawpi_app;

-- Plain log write (used for suppressions that are not a cap hit: quiet hours, pref off). Returns the row id,
-- or NULL when the user does not exist / the channel or outcome is not a known value.
create or replace function app_log_notification_send(
  p_user_id     integer,
  p_type        text,
  p_category    text,
  p_channel     text,
  p_subject_ref text,
  p_outcome     text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id bigint;
begin
  if p_user_id is null
     or p_channel not in ('push', 'email')
     or p_outcome not in ('sent', 'suppressed_cap', 'suppressed_quiet', 'suppressed_pref')
     or not exists (select 1 from user_profiles where id = p_user_id) then
    return null;
  end if;
  insert into notification_send_log (owner_user_id, type, category, channel, outcome, subject_ref)
  values (p_user_id, p_type, p_category, p_channel, p_outcome, p_subject_ref)
  returning id into v_id;
  return v_id;
end;
$$;

grant execute on function app_log_notification_send(integer, text, text, text, text, text) to pawpi_app;

-- Retention sweep (called by the receipts job): the log only needs to outlive the daily cap window plus a
-- debugging margin.
create or replace function app_notification_send_log_gc(p_older_than_days integer)
returns integer
language sql
security definer
set search_path = public, pg_temp
as $$
  with d as (
    delete from notification_send_log
     where sent_at < now() - make_interval(days => greatest(coalesce(p_older_than_days, 90), 7))
    returning 1
  )
  select count(*)::integer from d;
$$;

grant execute on function app_notification_send_log_gc(integer) to pawpi_app;

-- ── 4e. email consent (win-back) written from the unauthenticated unsubscribe link ─
-- The unsubscribe endpoint has NO session (the link is clicked from an inbox), so it cannot satisfy the
-- own-row notification_prefs policy. This DEFINER helper is the only cross-identity writer, and it accepts ONLY
-- the one email category that exists today, so it cannot be used to flip any other preference.
create or replace function app_set_email_consent(
  p_user_id  integer,
  p_category text,
  p_enabled  boolean
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if p_user_id is null
     or p_enabled is null
     or p_category is distinct from 'winback_email'
     or not exists (select 1 from user_profiles where id = p_user_id) then
    return false;
  end if;
  insert into notification_prefs (user_id, category, enabled)
  values (p_user_id, p_category, p_enabled)
  on conflict (user_id, category)
  do update set enabled = excluded.enabled, updated_at = now();
  return true;
end;
$$;

grant execute on function app_set_email_consent(integer, text, boolean) to pawpi_app;
