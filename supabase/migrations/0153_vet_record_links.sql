-- 0153_vet_record_links.sql
-- Sharing parts of the vet record by link, with no account (docs/vet-sharing-design.md, "Record links").
--
-- WHAT
--  1. care_record_links: one row per link the OWNER creates for ONE pet, with the sections they chose, an end date of
--     at most a year and whether notes may be added. Only sha256(token) is stored. ENABLE + FORCE RLS: only the owner
--     reads, creates or revokes their links; there is no delete policy.
--  2. vet_notes gains via_record_link, record_link_id and external_author_name: a note added through a link is marked,
--     and carries the signed-in author's display name or none. Its vet_name says it came from a shared link. Only the
--     database writes these three columns: not the application role.
--  3. app_record_link_view, app_record_link_file and app_record_link_add_note: the ONLY way a link holder reaches
--     anything. Each is keyed on the token hash and checks on every call that the link is not revoked, not expired and
--     that its owner still owns the pet, and answers for the granted sections only.
--  4. app_pet_has_vet_relationship no longer counts a note added through a link.
--  5. app_purge_finder_details (run hourly) also removes the record link sender counters after 90 days.
--
-- Links are a separate table from care_access_invites (0148): an invite created before this migration, or by an app that
-- predates record links, can never become a link that shows anything.
--
-- ADDITIVE and IDEMPOTENT. No row is changed or deleted, no existing policy is replaced, and the server deployed before
-- this migration keeps working with it (the new server also works without it and reports links as not available).
-- HAND-APPLIED after merge; then run supabase/verify_0153.sql (every row PASS).

-- ── 1. the table ───────────────────────────────────────────────────────────────────────────────────────────────
create table if not exists care_record_links (
  id             integer generated by default as identity primary key,
  pet_id         integer not null references pets(id) on delete cascade,
  owner_user_id  integer not null references user_profiles(id) on delete cascade,
  token_hash     text not null,
  sections       text[] not null,
  allow_notes    boolean not null default false,
  expires_at     timestamptz not null,
  revoked_at     timestamptz,
  created_at     timestamptz not null default now(),
  constraint care_record_links_hash_check check (token_hash ~ '^[0-9a-f]{64}$'),
  constraint care_record_links_sections_check check (
    cardinality(sections) > 0
    and array_position(sections, null) is null
    and sections <@ array['profile','emergency_contact','insurance','vet_notes','vaccines','files','photos','lab_results']::text[]
  ),
  constraint care_record_links_expiry_check
    check (expires_at > created_at and expires_at <= created_at + interval '366 days')
);

create unique index if not exists idx_care_record_links_hash on care_record_links (token_hash);
create index if not exists idx_care_record_links_owner on care_record_links (owner_user_id);
create index if not exists idx_care_record_links_pet on care_record_links (pet_id);

alter table care_record_links enable row level security;
alter table care_record_links force row level security;

drop policy if exists care_record_links_owner_select on care_record_links;
create policy care_record_links_owner_select on care_record_links
  for select
  using (owner_user_id = current_app_user_id());

drop policy if exists care_record_links_owner_insert on care_record_links;
create policy care_record_links_owner_insert on care_record_links
  for insert
  with check (
    owner_user_id = current_app_user_id()
    and app_owns_pet(pet_id)
    and revoked_at is null
  );

drop policy if exists care_record_links_owner_update on care_record_links;
create policy care_record_links_owner_update on care_record_links
  for update
  using (owner_user_id = current_app_user_id())
  with check (owner_user_id = current_app_user_id() and revoked_at is not null);

-- ── 2. notes added through a link ──────────────────────────────────────────────────────────────────────────────
alter table vet_notes add column if not exists via_record_link boolean not null default false;
alter table vet_notes add column if not exists record_link_id integer references care_record_links(id) on delete set null;
alter table vet_notes add column if not exists external_author_name text;

comment on column vet_notes.via_record_link is
  'True for a note added through a record link. Such a note is labelled as external and counts for no permission.';
comment on column vet_notes.external_author_name is
  'Display name of the signed-in person who added a note through a record link; null when they had no account or name.';

alter table vet_notes drop constraint if exists vet_notes_record_link_check;
alter table vet_notes add constraint vet_notes_record_link_check
  check (via_record_link or (record_link_id is null and external_author_name is null));

create index if not exists idx_vet_notes_record_link_id on vet_notes (record_link_id);

-- When the person who added a note through a link deletes their account, their name leaves the note too. Fires for the
-- foreign key's "set null" and for the account deletion that re-points authorship (0142).
create or replace function app_record_link_note_author_gone()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if old.via_record_link
     and old.external_author_name is not null
     and old.created_by_user_id is not null
     and new.created_by_user_id is distinct from old.created_by_user_id then
    new.external_author_name := 'Former member';
    new.vet_name := case when app_recipient_locale(new.owner_user_id) = 'en'
                         then 'Former member (shared link)' else 'Ex integrante (enlace compartido)' end;
  end if;
  return new;
end
$$;

drop trigger if exists vet_notes_record_link_author_gone on vet_notes;
create trigger vet_notes_record_link_author_gone
  before update of created_by_user_id on vet_notes
  for each row execute function app_record_link_note_author_gone();

-- The three record link columns are written only by app_record_link_add_note, the trigger above and the foreign keys,
-- all of which run as their owner. The application role neither sets nor changes them.
create or replace function app_vet_note_link_fields_guard()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if current_user = 'pawpi_app' then
    if tg_op = 'INSERT' then
      if new.via_record_link or new.record_link_id is not null or new.external_author_name is not null then
        raise exception 'vet_notes: the record link columns are written by the database only' using errcode = '42501';
      end if;
    elsif new.via_record_link is distinct from old.via_record_link
          or new.record_link_id is distinct from old.record_link_id
          or new.external_author_name is distinct from old.external_author_name then
      raise exception 'vet_notes: the record link columns are written by the database only' using errcode = '42501';
    end if;
  end if;
  return new;
end
$$;

-- Fires after the trigger above (triggers run in name order), so it sees the row as it will be stored.
drop trigger if exists vet_notes_record_link_guard on vet_notes;
create trigger vet_notes_record_link_guard
  before insert or update on vet_notes
  for each row execute function app_vet_note_link_fields_guard();

-- ── 3. what a link holder reaches ──────────────────────────────────────────────────────────────────────────────
-- The shared record as one value, or null when the link is unknown, revoked, expired or the pet changed owner. A section
-- that was not granted is null (single entry) or absent as null (list). No user id, no storage key, no file address:
-- a document or photo says only whether its file can be opened through the link.
create or replace function app_record_link_view(p_token_hash text)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select jsonb_build_object(
    'pet_name', p.name,
    -- An e-mail address is never shown as a name.
    'owner_name', case when position('@' in o.full_name) = 0 then nullif(btrim(o.full_name), '') end,
    'expires_at', l.expires_at,
    'allow_notes', l.allow_notes,
    'sections', to_jsonb(l.sections),
    'profile', (
      select jsonb_build_object(
        'microchip_id', mp.microchip_id,
        'spayed_neutered_status', mp.spayed_neutered_status,
        'spayed_neutered_date', mp.spayed_neutered_date,
        'primary_vet_name', mp.primary_vet_name,
        'primary_clinic_name', mp.primary_clinic_name,
        'vet_phone', mp.vet_phone,
        'vet_email', mp.vet_email,
        'medical_notes', mp.medical_notes)
      from pet_medical_profiles mp
      where 'profile' = any (l.sections)
        and mp.pet_id = l.pet_id and mp.owner_user_id = l.owner_user_id and mp.deleted_at is null
    ),
    'emergency_contact', (
      select jsonb_build_object(
        'emergency_contact_name', mp.emergency_contact_name,
        'emergency_contact_phone', mp.emergency_contact_phone)
      from pet_medical_profiles mp
      where 'emergency_contact' = any (l.sections)
        and mp.pet_id = l.pet_id and mp.owner_user_id = l.owner_user_id and mp.deleted_at is null
    ),
    'insurance', (
      select jsonb_build_object(
        'insurance_provider', mp.insurance_provider,
        'insurance_policy_number', mp.insurance_policy_number)
      from pet_medical_profiles mp
      where 'insurance' = any (l.sections)
        and mp.pet_id = l.pet_id and mp.owner_user_id = l.owner_user_id and mp.deleted_at is null
    ),
    'vet_notes', case when 'vet_notes' = any (l.sections) then coalesce((
      select jsonb_agg(jsonb_build_object(
        'note_date', n.note_date,
        'note', n.note,
        'vet_name', n.vet_name,
        'via_link', n.via_record_link,
        'external_author_name', n.external_author_name
      ) order by n.note_date desc, n.created_at desc, n.id desc)
      from vet_notes n
      where n.pet_id = l.pet_id and n.owner_user_id = l.owner_user_id
    ), '[]'::jsonb) end,
    'vaccines', case when 'vaccines' = any (l.sections) then coalesce((
      select jsonb_agg(jsonb_build_object(
        'name', v.name,
        'date_given', v.date_given,
        'expires_on', v.expires_on,
        'lot', v.lot,
        'clinic_name', v.clinic_name,
        'notes', v.notes
      ) order by v.date_given desc nulls last, v.created_at desc, v.id desc)
      from pet_vaccinations v
      where v.pet_id = l.pet_id and v.owner_user_id = l.owner_user_id and v.deleted_at is null
    ), '[]'::jsonb) end,
    'files', case when 'files' = any (l.sections) then coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', d.id,
        'name', d.name,
        'document_type', d.document_type,
        'document_date', d.document_date,
        'notes', d.notes,
        'file_available', d.file_url ~ ('^pets/' || l.pet_id::text || '/[A-Za-z0-9._-]+$') and strpos(d.file_url, '..') = 0
      ) order by d.document_date desc nulls last, d.created_at desc, d.id desc)
      from vet_documents d
      where d.pet_id = l.pet_id and d.owner_user_id = l.owner_user_id
    ), '[]'::jsonb) end,
    'photos', case when 'photos' = any (l.sections) then coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', h.id,
        'created_at', h.created_at,
        'body_area', h.body_area,
        'notes', h.notes,
        'file_available', h.image_url ~ ('^pets/' || l.pet_id::text || '/[A-Za-z0-9._-]+$') and strpos(h.image_url, '..') = 0
      ) order by h.created_at desc, h.id desc)
      from health_photo_checks h
      where h.pet_id = l.pet_id and h.owner_user_id = l.owner_user_id
    ), '[]'::jsonb) end,
    'lab_results', case when 'lab_results' = any (l.sections) then coalesce((
      select jsonb_agg(jsonb_build_object(
        'test_name', r.test_name,
        'test_date', r.test_date,
        'results', r.results,
        'ordered_by', r.ordered_by,
        'notes', r.notes
      ) order by r.test_date desc, r.created_at desc, r.id desc)
      from pet_lab_results r
      where r.pet_id = l.pet_id and r.owner_user_id = l.owner_user_id
    ), '[]'::jsonb) end
  )
  from care_record_links l
  join pets p
    on p.id = l.pet_id and p.owner_user_id = l.owner_user_id
  join user_profiles o
    on o.id = l.owner_user_id
  where l.token_hash = p_token_hash
    and l.revoked_at is null
    and l.expires_at > now()
$$;

-- One file of a granted section. No row: the link is unusable or the item is outside what it shares. A row with a null
-- key: the item is shared but its file is not a private file of this pet, so it is not opened through a link.
create or replace function app_record_link_file(p_token_hash text, p_kind text, p_item_id integer)
returns table (pet_id integer, media_key text)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select l.pet_id,
         case when f.ref ~ ('^pets/' || l.pet_id::text || '/[A-Za-z0-9._-]+$') and strpos(f.ref, '..') = 0
              then f.ref end
  from care_record_links l
  join pets p
    on p.id = l.pet_id and p.owner_user_id = l.owner_user_id
  cross join lateral (
    select d.file_url as ref
    from vet_documents d
    where p_kind = 'document' and 'files' = any (l.sections)
      and d.id = p_item_id and d.pet_id = l.pet_id and d.owner_user_id = l.owner_user_id
    union all
    select h.image_url
    from health_photo_checks h
    where p_kind = 'photo' and 'photos' = any (l.sections)
      and h.id = p_item_id and h.pet_id = l.pet_id and h.owner_user_id = l.owner_user_id
  ) f
  where l.token_hash = p_token_hash
    and l.revoked_at is null
    and l.expires_at > now()
$$;

-- Adds one vet note through a link that allows it: at most 10 per link in 24 hours. The link row is locked, so a
-- revocation lands fully before or after the note. The author is the identity of the request (current_app_user_id()),
-- never an argument: their display name, or no name at all.
-- outcome: 'added' | 'invalid' | 'not_allowed' | 'bad_note' | 'limit'.
create or replace function app_record_link_add_note(p_token_hash text, p_note text)
returns table (outcome text, added_on date, added_at timestamptz, author text)
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_link    care_record_links%rowtype;
  v_note    text := btrim(coalesce(p_note, ''), E' \t\r\n');
  v_user    integer := current_app_user_id();
  v_name    text;
  v_locale  text;
  v_zone    text;
  v_date    date;
  v_created timestamptz;
begin
  select l.* into v_link
  from care_record_links l
  where l.token_hash = p_token_hash
    and l.revoked_at is null
    and l.expires_at > now()
  for update;

  if not found
     or not exists (select 1 from pets p where p.id = v_link.pet_id and p.owner_user_id = v_link.owner_user_id) then
    return query select 'invalid'::text, null::date, null::timestamptz, null::text;
    return;
  end if;
  if not v_link.allow_notes then
    return query select 'not_allowed'::text, null::date, null::timestamptz, null::text;
    return;
  end if;
  if length(v_note) < 1 or length(v_note) > 2000 then
    return query select 'bad_note'::text, null::date, null::timestamptz, null::text;
    return;
  end if;
  if (select count(*) from vet_notes n
      where n.record_link_id = v_link.id and n.created_at > now() - interval '24 hours') >= 10 then
    return query select 'limit'::text, null::date, null::timestamptz, null::text;
    return;
  end if;

  if v_user is not null then
    select coalesce(nullif(btrim(u.full_name), ''), nullif(btrim(a.name), '')) into v_name
    from user_profiles u
    left join auth_users a on a.id = u.auth_user_id
    where u.id = v_user;
    v_name := nullif(btrim(left(regexp_replace(coalesce(v_name, ''), '[[:space:][:cntrl:]]+', ' ', 'g'), 80)), '');
    -- An e-mail address is never shown as a name.
    if position('@' in v_name) > 0 then
      v_name := null;
    end if;
  end if;

  select o.preferred_locale, o.timezone into v_locale, v_zone
  from user_profiles o
  where o.id = v_link.owner_user_id;
  begin
    v_date := (now() at time zone coalesce(nullif(btrim(v_zone), ''), 'America/Buenos_Aires'))::date;
  exception when others then
    v_date := (now() at time zone 'America/Buenos_Aires')::date;
  end;

  -- vet_name carries a label in the owner's language that says the note came from a shared link, so a screen that
  -- knows nothing about links reads it neither as the owner's own nor as one of their vets'.
  insert into vet_notes (
    pet_id, owner_user_id, vet_name, note_date, note, created_by_user_id,
    via_record_link, record_link_id, external_author_name
  ) values (
    v_link.pet_id, v_link.owner_user_id,
    coalesce(v_name, case when v_locale = 'en' then 'Anonymous' else 'Cambios de alguien externo' end)
      || case when v_locale = 'en' then ' (shared link)' else ' (enlace compartido)' end,
    v_date, v_note, v_user,
    true, v_link.id, v_name
  )
  returning vet_notes.created_at into v_created;

  return query select 'added'::text, v_date, v_created, v_name;
end
$$;

-- ── 4. a note added through a link unlocks nothing ─────────────────────────────────────────────────────────────
-- Same contract as 0147; the only change is "not vn.via_record_link".
create or replace function app_pet_has_vet_relationship(p_pet_id integer)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select
    exists (
      select 1
      from care_access_grants g
      join provider_capabilities pc
        on pc.provider_id = g.provider_id and pc.capability = 'vet'
      where g.pet_id = p_pet_id
        and g.status = 'active'
        and g.sections is null
        and (g.expires_at is null or g.expires_at > now())
    )
    or exists (
      select 1 from vet_notes vn where vn.pet_id = p_pet_id and not vn.via_record_link
    )
$$;

-- ── 5. retention of the sender counters ────────────────────────────────────────────────────────────────────────
-- Same contract as 0151; the only change is the record link buckets. The period stays equal to utils/finderRetention.js.
create or replace function app_purge_finder_details()
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_cleared integer;
begin
  update notifications
     set body = null,
         finder_contact = case
           when finder_contact ? 'pet_name' then jsonb_build_object('pet_name', finder_contact -> 'pet_name')
         end
   where type = 'emergency_contact'
     and created_at < now() - interval '90 days'
     and (body is not null or (finder_contact - 'pet_name') <> '{}'::jsonb);
  get diagnostics v_cleared = row_count;

  delete from rate_limit_hits
   where (bucket like 'emergency\_relay%' or bucket = 'emergency_public_read' or bucket like 'record\_link\_%')
     and window_start < now() - interval '90 days';

  return v_cleared;
end;
$$;

