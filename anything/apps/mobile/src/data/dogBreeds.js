// Case- AND accent-insensitive normalization: lowercase, strip diacritics
// (NFD + remove combining marks) so "Löwchen" matches "lowchen" and "MÉXICO"
// matches "mexico". Also collapses surrounding whitespace.
export function normalizeBreed(str) {
  return String(str ?? "")
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

// Filter the canonical list by a query, case/accent-insensitive substring match.
// An empty query returns the full list. `limit` (optional) caps the result count
// so the picker can render a bounded, non-scrolling list.
export function filterBreeds(query, limit) {
  const q = normalizeBreed(query);
  const matches = q
    ? DOG_BREEDS.filter((b) => normalizeBreed(b).includes(q))
    : DOG_BREEDS;
  return typeof limit === "number" ? matches.slice(0, limit) : matches;
}

// True when `query` exactly matches a canonical breed name (normalized) or the
// pinned "Mixed Breed" option — i.e. there is nothing custom to "Use".
export function hasExactBreedMatch(query) {
  const q = normalizeBreed(query);
  if (!q) return false;
  if (q === normalizeBreed("Mixed Breed")) return true;
  return DOG_BREEDS.some((b) => normalizeBreed(b) === q);
}
